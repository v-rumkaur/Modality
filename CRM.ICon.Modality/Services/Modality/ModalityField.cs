namespace CRM.ICon.Modality.Services.Modality
{
    public class ModalityField
    {
        /// <summary>
        /// The name of the modality
        /// </summary>
        public const string Name = "Name";

        /// <summary>
        /// A generic link that is associated with the modality
        /// </summary>
        public const string Link = "Link";

        /// <summary>
        /// A link to see if the modality is open now
        /// </summary>
        public const string OpenNowLink = "OpenNowLink";

        /// <summary>
        /// A link to see the hours of operation for the modality
        /// </summary>
        public const string HoopsLink = "HoopsLink";

        /// <summary>
        /// A link to see the length of the queue for the modality
        /// </summary>
        public const string QueueLength = "QueueLength";

        /// <summary>
        /// A link to see the wait time a customer would have if they request this modality
        /// </summary>
        public const string WaitTime = "WaitTime";

        /// <summary>
        /// The phone number associated with this modality
        /// </summary>
        public const string Phone = "Phone";

        /// <summary>
        /// The Article ID associated with this modality
        /// </summary>
        public const string ArticleId = "ArticleID";

        /// <summary>
        /// A link to see the availability of the queue for the modality
        /// </summary>
        public const string QueueAvailability = "QueueAvailability";
    }
}